CREATE TABLE room_watch_state (
 room_id UUID PRIMARY KEY REFERENCES rooms(id) ON DELETE CASCADE, provider VARCHAR(30) NOT NULL,
 media_id VARCHAR(200) NOT NULL, title VARCHAR(500), playing BOOLEAN NOT NULL DEFAULT false,
 position_seconds DOUBLE PRECISION NOT NULL DEFAULT 0, playback_rate DOUBLE PRECISION NOT NULL DEFAULT 1,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_by UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE
);
